def run_self_tests(cfg: Dict[str, Any] = CONFIG) -> pd.DataFrame:
    r = build_results(cfg)
    g, p, L = r["geometry"], r["pressure"], r["loads"]
    tests = []
    def test(name, condition, detail):
        tests.append({"Test":name,"Result":"PASS" if condition else "FAIL","Details":detail})
    test("Positive capacity",g["total_capacity_m3"]>0,f"V={g['total_capacity_m3']:.3f} m3")
    test("Pressure starts at zero",abs(p.iloc[0]["Vertical_pressure_kN_m2"])<1e-10,"Top boundary condition")
    test("Pressure non-decreasing",bool(np.all(np.diff(p["Vertical_pressure_kN_m2"])>=-1e-10)),"Janssen profile monotonicity")
    test("Horizontal pressure = K times vertical",bool(np.allclose(p["Horizontal_wall_pressure_kN_m2"],
         r["material"]["K"]*p["Vertical_pressure_kN_m2"])),"p_h = K p_v")
    test("Vertical equilibrium",abs(L["janssen_vertical_equilibrium_error_kN"])<1e-5,
         f"Residual={L['janssen_vertical_equilibrium_error_kN']:.8f} kN")
    test("Positive column reaction",L["gravity_reaction_per_column_kN"]>0,
         f"R={L['gravity_reaction_per_column_kN']:.3f} kN")
    test("Hoop provided steel >= membrane demand",
         r["reinforcement"]["hoop_bar_area_mm2"]*1000.0/r["reinforcement"]["hoop_bar_spacing_mm"]
         >= r["analysis"]["hoop_steel_tension_demand_mm2_per_m_height"],
         f"s={r['reinforcement']['hoop_bar_spacing_mm']:.2f} mm")
    out = pd.DataFrame(tests)
    if (out["Result"]=="FAIL").any():
        raise AssertionError("One or more silo self-tests failed.\n"+out.to_string(index=False))
    return out

