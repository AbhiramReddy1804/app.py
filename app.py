def plot_pressure(pressure: pd.DataFrame, show: bool = True) -> plt.Figure:
    fig, ax = plt.subplots(figsize=(7, 5))
    z = pressure["Depth_below_fill_surface_m"]
    ax.plot(pressure["Horizontal_wall_pressure_kN_m2"], z, label="Horizontal wall pressure")
    ax.plot(pressure["Vertical_pressure_kN_m2"], z, label="Vertical material pressure")
    ax.invert_yaxis(); ax.set_xlabel("Pressure (kN/m²)"); ax.set_ylabel("Depth below fill surface (m)")
