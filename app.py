def plot_silo_3d(cfg: Dict[str, Any], geom: Dict[str, float], analysis: Dict[str, Any],
                 show: bool = True) -> Optional[Any]:
    if not PLOTLY_AVAILABLE:
        print("Plotly is unavailable; skipping 3D visualization.")
        return
    Ri, Ro, rout = geom["internal_radius_m"], geom["outer_radius_m"], geom["outlet_radius_m"]
    Hc, Hh = geom["cylindrical_height_m"], geom["hopper_height_m"]
    theta = np.linspace(0, 2*np.pi, 80)
    zc = np.linspace(Hh, Hh+Hc, 24)
    T,Z = np.meshgrid(theta, zc)
    X = Ro*np.cos(T); Y = Ro*np.sin(T)
    fig = go.Figure()
    fig.add_trace(go.Surface(x=X,y=Y,z=Z,opacity=.45,showscale=False,name="Cylindrical wall"))
    # Cone shell surface: radius changes linearly from outlet to silo wall.
    v = np.linspace(0,1,24)
    V,TT = np.meshgrid(v,theta)
    R = rout + V*(Ri-rout)
    ZH = V*Hh
    XH,YH = R*np.cos(TT),R*np.sin(TT)
    fig.add_trace(go.Surface(x=XH,y=YH,z=ZH,opacity=.45,showscale=False,name="Conical hopper"))
    # Roof disk
    rr = np.linspace(0,Ro,20); TT2,RR = np.meshgrid(theta,rr)
    fig.add_trace(go.Surface(x=RR*np.cos(TT2),y=RR*np.sin(TT2),
                             z=np.full_like(RR,Hh+Hc),opacity=.35,showscale=False,name="Roof"))
    # Column solids as vertical line representations
    for i,(x,y) in enumerate(analysis["column_coordinates_m"]):
        fig.add_trace(go.Scatter3d(x=[x,x],y=[y,y],z=[Hh-cfg["column_height_m"],Hh],
                                   mode="lines",line=dict(width=9),name=f"Column {i+1}",showlegend=(i==0)))
    fig.update_layout(title="3D RCC Silo — Cylindrical Wall, Conical Hopper and Column Supports",
                      scene=dict(xaxis_title="X (m)",yaxis_title="Y (m)",zaxis_title="Z (m)",aspectmode="data"),
                      height=750)
    if show:
        display(fig)
    return fig

def build_results(cfg: Dict[str, Any] = CONFIG) -> Dict[str, Any]:
    validate_geometry(cfg)
    geom = silo_geometry(cfg)
    mat = material_properties(cfg)
    pressure = janssen_pressure_profile(cfg, geom, mat)
    loads = calculate_loads(cfg, geom, mat, pressure)
    analysis = structural_analysis(cfg, geom, mat, pressure, loads)
    rebar_df, rebar = reinforcement_design(cfg, geom, analysis)
    checks = run_checks(cfg, geom, mat, loads, analysis, rebar)
    bbs = build_hoop_bbs(cfg, rebar)
    return {"geometry": geom, "material": mat, "pressure": pressure,
            "loads": loads, "analysis": analysis,
            "reinforcement_table": rebar_df, "reinforcement": rebar,
            "bbs": bbs, "checks": checks}


