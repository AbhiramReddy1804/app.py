def validate_geometry(cfg: Dict[str, Any]) -> None:
    positive = [
        "outer_diameter_m", "cylindrical_height_m", "wall_thickness_m",
        "hopper_height_m", "outlet_diameter_m", "hopper_thickness_m",
        "concrete_unit_weight_kN_m3", "material_unit_weight_kN_m3",
        "number_of_columns", "column_width_m", "column_depth_m",
        "column_height_m", "fck_MPa", "fy_MPa", "nominal_cover_mm",
        "hoop_bar_diameter_mm", "maximum_hoop_bar_spacing_mm",
        "top_ring_beam_width_m", "top_ring_beam_depth_m",
        "outlet_ring_beam_width_m", "outlet_ring_beam_depth_m"
    ]
    for key in positive:
        if float(cfg[key]) <= 0:
            raise ValueError(f"{key} must be greater than zero.")
    if cfg["number_of_columns"] < 3 or int(cfg["number_of_columns"]) != cfg["number_of_columns"]:
        raise ValueError("number_of_columns must be an integer >= 3.")
    Di = cfg["outer_diameter_m"] - 2.0 * cfg["wall_thickness_m"]
    if Di <= 0:
        raise ValueError("Wall thickness leaves no positive internal diameter.")
    if cfg["outlet_diameter_m"] >= Di:
        raise ValueError("Outlet diameter must be smaller than the internal silo diameter.")
    if cfg["hopper_thickness_m"] >= cfg["hopper_height_m"]:
        raise ValueError("Hopper thickness must be smaller than hopper height.")
    if cfg["roof_type"] not in ("flat_slab", "none"):
        raise ValueError("roof_type must be 'flat_slab' or 'none'.")
    if cfg["roof_type"] == "flat_slab" and cfg["roof_thickness_m"] <= 0:
        raise ValueError("Roof thickness must be positive for a flat-slab roof.")
    if cfg["column_layout_radius_m"] <= 0:
        raise ValueError("Column layout radius must be positive.")


def silo_geometry(cfg: Dict[str, Any]) -> Dict[str, float]:
    validate_geometry(cfg)
    Do = float(cfg["outer_diameter_m"])
    tw = float(cfg["wall_thickness_m"])
    Di = Do - 2.0 * tw
    Ri, Ro = Di / 2.0, Do / 2.0
    rout = float(cfg["outlet_diameter_m"]) / 2.0
    Hc, Hh = float(cfg["cylindrical_height_m"]), float(cfg["hopper_height_m"])
    slant = math.hypot(Hh, Ri - rout)
    cone_angle = math.degrees(math.atan2(Hh, Ri - rout))  # generatrix to horizontal
    A_plan = math.pi * Ri**2
    V_cyl = A_plan * Hc
    V_cone = math.pi * Hh / 3.0 * (Ri**2 + Ri*rout + rout**2)
    V_total = V_cyl + V_cone
    A_cone = math.pi * (Ri + rout) * slant
    A_wall = 2.0 * math.pi * Ri * Hc
    V_wall_conc = math.pi / 4.0 * (Do**2 - Di**2) * Hc
    # Thin-shell quantity estimate using inner conical surface area.
    V_hopper_conc = A_cone * float(cfg["hopper_thickness_m"])
    V_roof_conc = (math.pi * Ri**2 * float(cfg["roof_thickness_m"])
                   if cfg["roof_type"] == "flat_slab" else 0.0)
    U = math.pi * Di
    V_top_ring = U * cfg["top_ring_beam_width_m"] * cfg["top_ring_beam_depth_m"]
    U_out = 2.0 * math.pi * rout
    V_out_ring = U_out * cfg["outlet_ring_beam_width_m"] * cfg["outlet_ring_beam_depth_m"]
    V_one_col = cfg["column_width_m"] * cfg["column_depth_m"] * cfg["column_height_m"]
    V_cols = cfg["number_of_columns"] * V_one_col
    return {
        "outer_diameter_m": Do, "internal_diameter_m": Di,
        "internal_radius_m": Ri, "outer_radius_m": Ro,
        "outlet_radius_m": rout, "cylindrical_height_m": Hc,
        "hopper_height_m": Hh, "hopper_slant_height_m": slant,
        "hopper_angle_to_horizontal_deg": cone_angle,
        "cylinder_plan_area_m2": A_plan, "cylinder_perimeter_m": U,
        "cylinder_volume_m3": V_cyl, "hopper_volume_m3": V_cone,
        "total_capacity_m3": V_total, "cylinder_wall_area_m2": A_wall,
        "hopper_surface_area_m2": A_cone,
        "wall_concrete_volume_m3": V_wall_conc,
        "hopper_concrete_volume_m3": V_hopper_conc,
        "roof_concrete_volume_m3": V_roof_conc,
        "top_ring_beam_concrete_volume_m3": V_top_ring,
        "outlet_ring_beam_concrete_volume_m3": V_out_ring,
        "columns_concrete_volume_m3": V_cols,
    }

def material_properties(cfg: Dict[str, Any]) -> Dict[str, float]:
    gamma = float(cfg["material_unit_weight_kN_m3"])
    phi = float(cfg["internal_friction_angle_deg"])
    delta = float(cfg["wall_friction_angle_deg"])
    K = float(cfg["lateral_pressure_ratio_K"])
    if gamma <= 0:
        raise ValueError("Material unit weight must be positive.")
    if not (0.0 <= phi < 60.0 and 0.0 <= delta < 60.0):
        raise ValueError("Friction angles must be between 0 and 60 degrees for this tool.")
    if K <= 0 or K > 2.0:
        raise ValueError("K must be > 0 and <= 2.0; enter a verified material/code value.")
    mu = math.tan(math.radians(delta))
    return {"gamma_kN_m3": gamma, "phi_deg": phi, "delta_deg": delta,
            "mu_wall": mu, "K": K}

def janssen_pressure_profile(cfg: Dict[str, Any], geom: Dict[str, float],
                              mat: Dict[str, float], n: int = 201) -> pd.DataFrame:
    """Symmetric static filling pressure in the vertical cylindrical section.

    For a circular section A/U = D/4:
      p_v(z) = gamma*D/(4*mu*K) * (1-exp(-4*mu*K*z/D))
      p_h(z) = K*p_v(z); tau_w(z) = mu*p_h(z)
    If mu -> 0, the limiting solution p_v = gamma*z is used.
    This is an analytical Janssen model, not a complete filling/discharge load set.
    """
    D = geom["internal_diameter_m"]
    H = geom["cylindrical_height_m"]
    gamma, mu, K = mat["gamma_kN_m3"], mat["mu_wall"], mat["K"]
    z = np.linspace(0.0, H, int(n))
    a = 4.0 * mu * K / D
    if abs(a) < 1e-12:
        pv = gamma * z
    else:
        pv = gamma / a * (1.0 - np.exp(-a*z))
    ph = K * pv
    tau = mu * ph
    return pd.DataFrame({"Depth_below_fill_surface_m": z,
                         "Vertical_pressure_kN_m2": pv,
                         "Horizontal_wall_pressure_kN_m2": ph,
                         "Wall_shear_kN_m2": tau})


def calculate_loads(cfg: Dict[str, Any], geom: Dict[str, float],
                    mat: Dict[str, float], pressure: pd.DataFrame) -> Dict[str, float]:
    gamma_c = float(cfg["concrete_unit_weight_kN_m3"])
    gamma_m = mat["gamma_kN_m3"]
    H, D, A, U = (geom["cylindrical_height_m"], geom["internal_diameter_m"],
                  geom["cylinder_plan_area_m2"], geom["cylinder_perimeter_m"])
    mu, K = mat["mu_wall"], mat["K"]
    pv_base = float(pressure.iloc[-1]["Vertical_pressure_kN_m2"])
    ph_base = float(pressure.iloc[-1]["Horizontal_wall_pressure_kN_m2"])
    tau_base = float(pressure.iloc[-1]["Wall_shear_kN_m2"])
    # Integrated wall friction per unit circumferential length (kN/m).
    if mu == 0.0 or K == 0.0:
        wall_friction_per_m = 0.0
    else:
        a = 4.0 * mu * K / D
        wall_friction_per_m = mu * K * (gamma_m/a) * (H - (1.0 - math.exp(-a*H))/a)
    total_wall_friction = wall_friction_per_m * U
    vertical_force_at_cylinder_base = pv_base * A
    cylinder_material_weight = geom["cylinder_volume_m3"] * gamma_m
    equilibrium_error = (vertical_force_at_cylinder_base + total_wall_friction
                         - cylinder_material_weight)

    W_material = geom["total_capacity_m3"] * gamma_m
    W_wall = geom["wall_concrete_volume_m3"] * gamma_c
    W_hopper = geom["hopper_concrete_volume_m3"] * gamma_c
    W_roof = geom["roof_concrete_volume_m3"] * gamma_c
    W_top_ring = geom["top_ring_beam_concrete_volume_m3"] * gamma_c
    W_out_ring = geom["outlet_ring_beam_concrete_volume_m3"] * gamma_c
    W_columns = geom["columns_concrete_volume_m3"] * gamma_c
    roof_live = (geom["cylinder_plan_area_m2"] * cfg["roof_live_load_kN_m2"]
                 if cfg["roof_type"] == "flat_slab" and cfg["include_roof_live_load_in_gravity_reaction"]
                 else 0.0)
    total_gravity = (W_material + W_wall + W_hopper + W_roof + W_top_ring
                     + W_out_ring + W_columns + roof_live)
    ncol = int(cfg["number_of_columns"])
    return {
        "vertical_pressure_at_cylinder_base_kN_m2": pv_base,
        "horizontal_pressure_at_cylinder_base_kN_m2": ph_base,
        "wall_shear_at_cylinder_base_kN_m2": tau_base,
        "wall_friction_resultant_per_m_circumference_kN_m": wall_friction_per_m,
        "total_cylinder_wall_friction_kN": total_wall_friction,
        "vertical_resultant_at_cylinder_base_kN": vertical_force_at_cylinder_base,
        "cylinder_material_weight_kN": cylinder_material_weight,
        "janssen_vertical_equilibrium_error_kN": equilibrium_error,
        "stored_material_weight_total_kN": W_material,
        "cylindrical_wall_self_weight_kN": W_wall,
        "hopper_shell_self_weight_kN": W_hopper,
        "roof_slab_self_weight_kN": W_roof,
        "top_ring_beam_self_weight_kN": W_top_ring,
        "outlet_ring_beam_self_weight_kN": W_out_ring,
        "column_self_weight_total_kN": W_columns,
        "roof_live_load_total_kN": roof_live,
        "total_gravity_load_kN": total_gravity,
        "gravity_reaction_per_column_kN": total_gravity/ncol,
    }

def structural_analysis(cfg: Dict[str, Any], geom: Dict[str, float],
                         mat: Dict[str, float], pressure: pd.DataFrame,
                         loads: Dict[str, float]) -> Dict[str, float]:
    """Preliminary circular wall membrane actions.

    Hoop membrane force per metre of wall height: N_theta = p_h * r.
    Axial wall compression from stored-material wall friction is reported as a
    resultant; it is not a shell buckling or combined-stress verification.
    """
    r = geom["internal_radius_m"]
    t_mm = cfg["wall_thickness_m"] * 1000.0
    ph = pressure["Horizontal_wall_pressure_kN_m2"].to_numpy()
    z = pressure["Depth_below_fill_surface_m"].to_numpy()
    hoop = ph * r  # kN/m vertical height
    Ntheta_max = float(np.max(hoop))
    # Characteristic membrane hoop tension converted to steel area per metre height.
    fy = float(cfg["fy_MPa"])
    if fy <= 0:
        raise ValueError("Steel yield strength must be positive.")
    Ast_hoop_total = Ntheta_max * 1000.0 / (0.87 * fy)  # mm2 per m height
    wall_axial_friction = loads["total_cylinder_wall_friction_kN"] / geom["cylinder_perimeter_m"]
    wall_self_weight_per_m = (loads["cylindrical_wall_self_weight_kN"]
                              / geom["cylinder_perimeter_m"])
    axial_compression_per_m = wall_axial_friction + wall_self_weight_per_m
    axial_stress = axial_compression_per_m / t_mm  # N/mm2
    # Circular column layout; coordinates for a symmetric ring.
    ncol = int(cfg["number_of_columns"])
    radius = float(cfg["column_layout_radius_m"])
    col_xy = [(radius*math.cos(2*math.pi*i/ncol),
               radius*math.sin(2*math.pi*i/ncol)) for i in range(ncol)]
    return {
        "maximum_hoop_tension_kN_per_m_height": Ntheta_max,
        "hoop_steel_tension_demand_mm2_per_m_height": Ast_hoop_total,
        "wall_vertical_compression_from_friction_kN_per_m_circumference": wall_axial_friction,
        "wall_self_weight_per_m_circumference_kN_m": wall_self_weight_per_m,
        "wall_axial_compression_total_kN_per_m_circumference": axial_compression_per_m,
        "average_wall_axial_compressive_stress_MPa": axial_stress,
        "column_coordinates_m": col_xy,
    }

def bar_area_mm2(d_mm: float) -> float:
    if d_mm <= 0:
        raise ValueError("Bar diameter must be positive.")
    return math.pi*d_mm**2/4.0


def reinforcement_design(cfg: Dict[str, Any], geom: Dict[str, float],
                          analysis: Dict[str, float]) -> Tuple[pd.DataFrame, Dict[str, float]]:
    """Hoop tension steel demand and illustrative circular ring-bar quantity.

    Does not check IS 456 minimum steel, crack width, anchorage, lap location,
    temperature/shrinkage, vertical steel, local openings or shell bending.
    """
    d = float(cfg["hoop_bar_diameter_mm"])
    smax = float(cfg["maximum_hoop_bar_spacing_mm"])
    if smax <= 0:
        raise ValueError("Maximum hoop bar spacing must be positive.")
    Ast_req = analysis["hoop_steel_tension_demand_mm2_per_m_height"]
    Ab = bar_area_mm2(d)
    s_theory = (Ab*1000.0/Ast_req) if Ast_req > 0 else smax
    s_prov = min(smax, s_theory)
    Ast_prov = Ab*1000.0/s_prov
    n_rings = int(math.ceil(geom["cylindrical_height_m"]*1000.0/s_prov))+1
    circumference = math.pi*geom["internal_diameter_m"]
    lap = float(cfg["hoop_bar_lap_allowance_m"])
    length_each = circumference + lap
    total_length = n_rings*length_each
    unit_mass = d*d/162.0  # kg/m, standard nominal estimate
    total_mass = total_length*unit_mass
    df = pd.DataFrame([
        {"Element": "Circular wall hoop reinforcement (tension demand only)",
         "Required_steel_mm2_per_m_height": Ast_req,
         "Bar_diameter_mm": d, "Calculated_spacing_mm": s_theory,
         "Adopted_spacing_mm": s_prov,
         "Provided_steel_mm2_per_m_height": Ast_prov,
         "Status": "DEMAND ONLY - minimum steel/crack control/detailing pending"}
    ])
    summary = {"hoop_bar_area_mm2": Ab, "hoop_bar_spacing_mm": s_prov,
               "hoop_bar_count_rings": n_rings,
               "hoop_bar_length_each_m": length_each,
               "hoop_bar_total_length_m": total_length,
               "hoop_bar_unit_mass_kg_m": unit_mass,
               "hoop_bar_total_mass_kg": total_mass}
    return df, summary


