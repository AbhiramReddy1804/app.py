def run_checks(cfg: Dict[str, Any], geom: Dict[str, float],
               mat: Dict[str, float], loads: Dict[str, float],
               analysis: Dict[str, float], rebar: Dict[str, float]) -> pd.DataFrame:
    checks: List[Dict[str, str]] = []
    def add(name: str, ok: bool, detail: str):
        checks.append({"Check": name, "Status": "PASS" if ok else "REVIEW", "Details": detail})
    add("Positive internal diameter", geom["internal_diameter_m"] > 0,
        f"Di = {geom['internal_diameter_m']:.3f} m")
    add("Outlet smaller than silo", geom["outlet_radius_m"] < geom["internal_radius_m"],
        f"Do,outlet = {2*geom['outlet_radius_m']:.3f} m; Di = {geom['internal_diameter_m']:.3f} m")
